using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;

using FluentAssertions;

using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;

using NetworkPerspective.Sync.Orchestrator.Application.Infrastructure.Persistence;
using NetworkPerspective.Sync.Orchestrator.Persistence.Entities;
using NetworkPerspective.Sync.Orchestrator.Persistence.Schema;

using Xunit;

namespace NetworkPerspective.Sync.Orchestrator.Persistence.Tests;

public class PostgreSqlCompatibilityTests
{
    [Theory]
    [InlineData(null, DatabaseProvider.SqlServer)]
    [InlineData("SqlServer", DatabaseProvider.SqlServer)]
    [InlineData("PostgreSql", DatabaseProvider.PostgreSql)]
    [InlineData("postgresql", DatabaseProvider.PostgreSql)]
    public void SelectsOnlyExplicitSupportedProvider(string configured, DatabaseProvider expected)
    {
        var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string>
        {
            ["Database:Provider"] = configured
        }).Build();
        config.GetDatabaseProvider().Should().Be(expected);
        using var context = new OrchestratorDbContext(UnitOfWorkFactory.CreateOptions(expected, ""));
        context.Database.ProviderName.Should().Be(expected == DatabaseProvider.SqlServer
            ? "Microsoft.EntityFrameworkCore.SqlServer" : "Npgsql.EntityFrameworkCore.PostgreSQL");
    }

    [Theory]
    [InlineData("")]
    [InlineData("PostgresTypo")]
    [InlineData("1")]
    public void InvalidProviderFailsClosed(string value)
    {
        var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string>
        {
            ["Database:Provider"] = value
        }).Build();
        Action act = () => config.GetDatabaseProvider();
        act.Should().Throw<InvalidOperationException>();
    }

    [Fact]
    public void OnlyLegacyStartupRegistersSchemaInitializer()
    {
        var legacy = new ServiceCollection().AddStartupDbInitializer();
        legacy.Should().ContainSingle(x => x.ServiceType == typeof(IHostedService));
        var ovh = new ServiceCollection().AddStartupDbInitializer(DatabaseProvider.PostgreSql);
        ovh.Should().NotContain(x => x.ServiceType == typeof(IHostedService));
    }

    [Fact]
    public async Task DirectPostgresMigrationCannotRunSqlServerHistory()
    {
        using var uow = new UnitOfWork(UnitOfWorkFactory.CreateOptions(DatabaseProvider.PostgreSql,
            "Host=database.example.invalid;Database=synthetic"));
        Func<Task> migrate = () => uow.MigrateAsync();
        await migrate.Should().ThrowAsync<InvalidOperationException>().WithMessage("*separately reviewed*");
    }

    [Fact]
    public void GeneratesFreshApplicationAndVersionMatchedQuartzSchemaOffline()
    {
        var script = PostgreSqlSchema.GenerateScript();
        foreach (var table in new[] { "Workers", "Connectors", "ConnectorProperties", "SyncHistory", "StatusLogs", "DbSecrets" })
            script.Should().Contain($"CREATE TABLE \"{table}\"");
        script.Should().Contain("uuid").And.Contain("timestamp with time zone")
            .And.Contain("GENERATED BY DEFAULT AS IDENTITY")
            .And.Contain("CREATE TABLE qrtz_job_details")
            .And.Contain("CREATE TABLE qrtz_triggers")
            .And.Contain("misfire_orig_fire_time")
            .And.Contain("execution_group")
            .And.Contain("BEGIN;").And.Contain("COMMIT;")
            .And.NotContain("DROP TABLE").And.NotContain("__EFMigrationsHistory")
            .And.NotContain("nvarchar").And.NotContain("IDENTITY(1,1)");
    }

    [Fact]
    public void MapsAllStoredDatesToUtcWithoutChangingLegacyMapping()
    {
        using var pg = new OrchestratorDbContext(UnitOfWorkFactory.CreateOptions(DatabaseProvider.PostgreSql, ""));
        var dates = pg.Model.GetEntityTypes().SelectMany(x => x.GetProperties()).Where(x => x.ClrType == typeof(DateTime)).ToArray();
        dates.Should().HaveCount(6);
        foreach (var property in dates)
        {
            property.GetColumnType().Should().Be("timestamp with time zone");
            var unspecified = new DateTime(2026, 1, 2, 3, 4, 5, DateTimeKind.Unspecified);
            var converted = (DateTime)property.GetValueConverter().ConvertToProvider(unspecified);
            converted.Kind.Should().Be(DateTimeKind.Utc);
            converted.Ticks.Should().Be(unspecified.Ticks);
        }
        using var sql = new OrchestratorDbContext(UnitOfWorkFactory.CreateOptions(DatabaseProvider.SqlServer, ""));
        sql.Model.FindEntityType(typeof(WorkerEntity)).FindProperty(nameof(WorkerEntity.CreatedAt))
            .GetValueConverter().Should().BeNull();
    }
}